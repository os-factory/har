import { execFileSync } from 'child_process';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';

/**
 * `har env status` slot discovery, end to end through the built CLI (#474).
 *
 * A sandbox HOME holds a real repository with a cli-profile harness (no PM2),
 * a real `git worktree add` session worktree for slot 1 under
 * `~/worktrees/<name>-har-agent-1-<suffix>`, and decoys: worktrees of a
 * DIFFERENT repository whose names also match `-har-agent-1-` and that also
 * carry `.env.agent.1`. They sort before the real slot, so a resolver that
 * stopped checking repository identity would pick one.
 *
 * Status must resolve slot 1 to the right worktree from the slot registry and,
 * with the registry gone, from the `~/worktrees` scan — and it must stay cheap:
 * a spawn tracer records every child process the CLI starts, and the guard
 * asserts no `pm2` for a non-PM2 harness and no `git rev-parse
 * --git-common-dir` per candidate (common dirs are read from disk).
 *
 * No daemons, no Docker, no network: runs in the normal unit suite and in CI.
 */

const ROOT = path.resolve(__dirname, '..');
const HAR_BIN = path.join(ROOT, 'dist', 'index.js');
const TRACER = path.join(__dirname, 'helpers', 'spawn-tracer.cjs');
const DECOYS = 10;

interface SlotJson {
  agentId: number;
  active: boolean;
  workDir?: string;
  worktreePath?: string;
  branch?: string;
  pm2Issue?: string;
}
interface StatusJson {
  harnessRoot: string;
  slots: SlotJson[];
}
interface TraceRow {
  fn: string;
  command: string;
}

describe('har env status slot discovery (built CLI, sandbox HOME)', () => {
  let base: string;
  let home: string;
  let repo: string;
  let decoyRepo: string;
  let realSlot: string;
  const decoySlots: string[] = [];
  let traceSeq = 0;
  let baselineTrace: TraceRow[] = [];

  const env = (extra: Record<string, string> = {}): NodeJS.ProcessEnv => {
    const out: NodeJS.ProcessEnv = {
      ...process.env,
      HOME: home,
      PM2_HOME: path.join(home, '.pm2'),
      HAR_TELEMETRY: 'off',
      HAR_SKIP_TELEMETRY_POSTINSTALL: '1',
      GIT_AUTHOR_NAME: 'e2e',
      GIT_AUTHOR_EMAIL: 'e2e@example.com',
      GIT_COMMITTER_NAME: 'e2e',
      GIT_COMMITTER_EMAIL: 'e2e@example.com',
      GIT_CONFIG_NOSYSTEM: '1',
      ...extra,
    };
    // The developer's (or CI's) git context must not leak into the sandbox.
    for (const key of ['GIT_DIR', 'GIT_WORK_TREE', 'GIT_COMMON_DIR', 'GIT_INDEX_FILE']) {
      delete out[key];
    }
    return out;
  };
  const git = (cwd: string, ...args: string[]) =>
    execFileSync('git', ['-c', 'commit.gpgsign=false', ...args], {
      cwd,
      env: env(),
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
  const har = (args: string[], extra: Record<string, string> = {}) =>
    execFileSync(process.execPath, [HAR_BIN, ...args], {
      cwd: repo,
      env: env(extra),
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      timeout: 60_000,
    });

  /** `har env status --json`, with every child process the CLI spawns traced. */
  function tracedStatus(): { status: StatusJson; trace: TraceRow[] } {
    const traceFile = path.join(base, `trace-${++traceSeq}.jsonl`);
    const out = har(['env', 'status', '--json', '--repo', repo], {
      NODE_OPTIONS: `--require ${TRACER}`,
      HAR_SPAWN_TRACE: traceFile,
    });
    const trace = fs.existsSync(traceFile)
      ? fs
          .readFileSync(traceFile, 'utf8')
          .split('\n')
          .filter(Boolean)
          .map((line) => JSON.parse(line) as TraceRow)
      : [];
    return { status: JSON.parse(out) as StatusJson, trace };
  }

  const slot = (status: StatusJson, id: number) => {
    const found = status.slots.find((s) => s.agentId === id);
    if (!found) throw new Error(`slot ${id} missing from status`);
    return found;
  };
  const pm2Calls = (trace: TraceRow[]) => trace.filter((r) => /\bpm2\b/.test(r.command));
  const commonDirCalls = (trace: TraceRow[]) =>
    trace.filter((r) => /rev-parse\b.*--git-common-dir/.test(r.command));
  const registryFile = () => path.join(repo, '.har', 'slots', 'agent-1.json');

  function writeEnvFile(workDir: string) {
    // The template-less env file launch writes for cli harnesses.
    fs.writeFileSync(
      path.join(workDir, '.env.agent.1'),
      ['# Agent environment — generated by launch.sh', 'AGENT_ID=1', `REPO_ROOT=${workDir}`, `WORKTREE_DIR=${workDir}`, 'NODE_ENV=test', ''].join('\n'),
    );
  }

  function writeRegistry() {
    // Field order mirrors writeSlotRegistry (src/core/slot-registry.ts), as launch writes it.
    fs.mkdirSync(path.dirname(registryFile()), { recursive: true });
    const entry = {
      version: 1,
      agentId: 1,
      projectName: 'proj',
      mode: 'worktree',
      workDir: realSlot,
      createdAt: new Date().toISOString(),
      status: 'active',
      suffix: 'zz9q',
      worktreePath: realSlot,
      branch: 'proj-har-agent-1-zz9q',
      baseBranch: 'main',
      baseCommit: git(repo, 'rev-parse', 'main').trim(),
    };
    fs.writeFileSync(registryFile(), JSON.stringify(entry, null, 2) + '\n');
  }

  beforeAll(() => {
    if (!fs.existsSync(HAR_BIN)) {
      execFileSync('npm', ['run', 'build'], { cwd: ROOT, stdio: 'ignore' });
    }
    base = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'har-status-discovery-')));
    home = path.join(base, 'home');
    repo = path.join(home, 'src', 'proj');
    decoyRepo = path.join(home, 'src', 'other');
    const worktrees = path.join(home, 'worktrees');
    fs.mkdirSync(worktrees, { recursive: true });

    // The project: a real repository with a committed cli-profile harness (no PM2).
    fs.mkdirSync(repo, { recursive: true });
    git(repo, 'init', '-q', '-b', 'main');
    fs.writeFileSync(path.join(repo, 'README.md'), '# proj\n');
    git(repo, 'add', '-A');
    git(repo, 'commit', '-qm', 'init');
    har(['env', 'init', '--profile', 'cli', '--yes', '--no-cursor-rule', '--no-agents', '--commit-gate', 'never']);
    git(repo, 'add', '-A');
    git(repo, 'commit', '-qm', 'har');

    // Slot 1: a real linked worktree, as launch creates it.
    realSlot = path.join(worktrees, 'proj-har-agent-1-zz9q');
    git(repo, 'worktree', 'add', '-q', '-b', 'proj-har-agent-1-zz9q', realSlot);
    writeEnvFile(realSlot);

    // Baseline cost with the real slot only, on the registry-missing scan path.
    baselineTrace = tracedStatus().trace;

    // Decoys: worktrees of ANOTHER repository with matching names and env files,
    // named to sort before the real slot.
    fs.mkdirSync(decoyRepo, { recursive: true });
    git(decoyRepo, 'init', '-q', '-b', 'main');
    fs.writeFileSync(path.join(decoyRepo, 'README.md'), '# other\n');
    git(decoyRepo, 'add', '-A');
    git(decoyRepo, 'commit', '-qm', 'init');
    for (let i = 0; i < DECOYS; i++) {
      const dir = path.join(worktrees, `a-decoy-${String(i).padStart(2, '0')}-har-agent-1-x${i}`);
      git(decoyRepo, 'worktree', 'add', '-q', '-b', `decoy-${i}`, dir);
      writeEnvFile(dir);
      decoySlots.push(dir);
    }
    // And one that is not a git checkout at all.
    const plain = path.join(worktrees, 'a-plain-har-agent-1-p0');
    fs.mkdirSync(plain);
    writeEnvFile(plain);
    decoySlots.push(plain);
  }, 120_000);

  afterAll(() => {
    if (base) fs.rmSync(base, { recursive: true, force: true });
  });

  it('resolves slot 1 from the slot registry, ignoring decoy worktrees of another repository', () => {
    writeRegistry();
    const { status, trace } = tracedStatus();
    const s1 = slot(status, 1);
    expect(status.harnessRoot).toBe(repo);
    expect(s1.active).toBe(true);
    expect(s1.worktreePath).toBe(realSlot);
    expect(s1.workDir).toBe(realSlot);
    expect(s1.branch).toBe('proj-har-agent-1-zz9q');
    expect(s1.pm2Issue).toBeUndefined();
    // Decoys are agent-1 only: no other slot may pick one up.
    for (const other of status.slots.filter((s) => s.agentId !== 1)) {
      expect(other.active).toBe(false);
      expect(decoySlots).not.toContain(other.worktreePath);
    }
    expect(pm2Calls(trace)).toEqual([]);
    expect(commonDirCalls(trace).length).toBeLessThanOrEqual(2);
  });

  it('falls back to the ~/worktrees scan when the registry is missing, and still skips the decoys', () => {
    fs.rmSync(registryFile(), { force: true });
    const { status } = tracedStatus();
    const s1 = slot(status, 1);
    expect(s1.active).toBe(true);
    expect(s1.worktreePath).toBe(realSlot);
    expect(s1.workDir).toBe(realSlot);
    expect(s1.branch).toBe('proj-har-agent-1-zz9q');
    expect(decoySlots).not.toContain(s1.worktreePath);
    expect(decoySlots).not.toContain(s1.workDir);
  });

  it('stays cheap: no pm2 for a non-PM2 harness, and no git process per ~/worktrees candidate', () => {
    fs.rmSync(registryFile(), { force: true });
    const { trace } = tracedStatus();

    expect(pm2Calls(baselineTrace)).toEqual([]);
    expect(pm2Calls(trace)).toEqual([]);

    // Common dirs come from disk: at most a couple of git fallbacks, however
    // many candidates sit in ~/worktrees.
    expect(commonDirCalls(trace).length).toBeLessThanOrEqual(2);
    expect(commonDirCalls(trace).length).toBe(commonDirCalls(baselineTrace).length);

    // Adding DECOYS matching candidates must not add a single git process.
    const gitCount = (rows: TraceRow[]) => rows.filter((r) => /^git\b/.test(r.command)).length;
    expect(gitCount(trace)).toBe(gitCount(baselineTrace));
    // Sanity: the tracer saw the CLI's own git calls, so a zero above is real.
    expect(gitCount(trace)).toBeGreaterThan(0);
  });
});
